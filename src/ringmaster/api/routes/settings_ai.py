@router.post("/update-worker/{worker_id}")
async def update_worker_from_nl(
    worker_id: str,
    db: Annotated[Database, Depends(get_db)],
    body: UpdateWorkerFromNLRequest,
) -> NLToSettingsResponse:
    """Update an existing worker from natural language description.

    This endpoint combines:
    1. AI interpretation of natural language changes
    2. Worker update in the database

    Example request:
    {
        "natural_language": "Add TypeScript capabilities and change description to focus on frontend"
    }

    The AI will:
    - Parse the current worker state
    - Apply the requested changes
    - Generate updated settings
    - Update the worker in the database
    """
    from ringmaster.db import WorkerRepository
    from ringmaster.domain import Worker

    provider = get_llm_provider()

    if provider == "none":
        return NLToSettingsResponse(
            success=False,
            error="No LLM provider available. Install Claude Code CLI, or set ANTHROPIC_API_KEY or OPENAI_API_KEY environment variable.",
        )

    # Get current worker
    worker_repo = WorkerRepository(db)
    current_worker = await worker_repo.get(worker_id)

    if not current_worker:
        return NLToSettingsResponse(
            success=False,
            error=f"Worker {worker_id} not found",
        )

    try:
        # Generate updated settings using local Claude Code with current state
        logger.info(f"Generating worker updates from natural language for {worker_id}")
        result_text = await call_claude_code_for_update(body.natural_language, current_worker)

        # Parse JSON response
        settings_data = json.loads(result_text)
        new_settings = WorkerSettingsFromAI(**settings_data)

        # Update worker with only the fields that were returned
        if new_settings.name is not None:
            current_worker.name = new_settings.name
        if new_settings.description is not None:
            current_worker.description = new_settings.description
        if new_settings.type is not None:
            current_worker.type = new_settings.type
        if new_settings.generated_script is not None:
            current_worker.generated_script = new_settings.generated_script
        if new_settings.capabilities is not None:
            current_worker.capabilities = new_settings.capabilities

        # Save to database
        updated_worker = await worker_repo.update(current_worker)

        logger.info(f"Worker updated from NL: id={updated_worker.id}, name={updated_worker.name}")

        return NLToSettingsResponse(
            success=True,
            settings=settings_data,
            worker_settings=new_settings,
        )

    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse LLM response as JSON: {e}")
        logger.debug(f"LLM response text: {result_text}")
        return NLToSettingsResponse(
            success=False,
            error=f"Failed to parse LLM response as JSON: {str(e)}",
        )
    except Exception as e:
        logger.error(f"Error updating worker from NL: {e}")
        return NLToSettingsResponse(
            success=False,
            error=str(e),
        )
