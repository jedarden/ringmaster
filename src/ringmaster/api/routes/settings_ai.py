@router.post("/nl-to-settings", response_model=NLToSettingsResponse)
async def natural_language_to_settings(
    db: Annotated[Database, Depends(get_db)],
    body: NLToSettingsRequest,
) -> NLToSettingsResponse:
    """Convert natural language description to structured settings.

    Priority:
    1. Local Claude Code CLI (claude command) - uses existing auth
    2. Anthropic API (ANTHROPIC_API_KEY)
    3. OpenAI API (OPENAI_API_KEY)

    Local Claude Code is preferred as it reuses your existing authentication
    and monthly plan if available.
    """
    provider = get_llm_provider()

    if provider == "none":
        logger.warning("No LLM provider available")
        return NLToSettingsResponse(
            success=False,
            error="No LLM provider available. Install Claude Code CLI, or set ANTHROPIC_API_KEY or OPENAI_API_KEY environment variable.",
        )

    try:
        # Try local Claude Code first
        if provider == "claude-code-local":
            logger.info(f"Using local Claude Code CLI for {body.settings_type} settings")
            result_text = await call_claude_code_local(body.natural_language)
        # Fall back to external APIs
        elif provider == "anthropic":
            logger.info(f"Calling Anthropic API for {body.settings_type} settings")
            result_text = await call_anthropic_api(body.natural_language)
        else:  # openai
            logger.info(f"Calling OpenAI API for {body.settings_type} settings")
            result_text = await call_openai_api(body.natural_language)

        # Clean up the response - remove markdown code blocks if present
        result_text = result_text.strip()
        if result_text.startswith("```"):
            # Remove markdown code block markers
            lines = result_text.split("\n")
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines[-1].startswith("```"):
                lines = lines[:-1]
            result_text = "\n".join(lines)

        # Parse JSON response
        settings_data = json.loads(result_text)

        # Create worker settings response
        worker_settings = WorkerSettingsFromAI(**settings_data)

        logger.info(f"Successfully generated {body.settings_type} settings from natural language")

        return NLToSettingsResponse(
            success=True,
            settings=settings_data,
            worker_settings=worker_settings,
            reasoning=worker_settings.reasoning,
        )

    except httpx.HTTPStatusError as e:
        logger.error(f"LLM API error: {e.response.status_code} - {e.response.text}")
        return NLToSettingsResponse(
            success=False,
            error=f"LLM API error: {e.response.status_code}",
        )
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse LLM response as JSON: {e}")
        logger.debug(f"LLM response text: {result_text}")
        return NLToSettingsResponse(
            success=False,
            error=f"Failed to parse LLM response as JSON: {str(e)}",
        )
    except Exception as e:
        logger.error(f"Error converting natural language to settings: {e}")
        return NLToSettingsResponse(
            success=False,
            error=str(e),
        )


